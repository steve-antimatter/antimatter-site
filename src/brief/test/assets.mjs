// Shop assets: stages, rules and the prompt pack.
import fs from 'fs';
import assert from 'assert/strict';
import { d1 } from '../../usecase/test/d1-shim.mjs';
import { ensureSchema, saveDoc } from '../../usecase/store.js';
import { createBrief, patchBrief, setBriefStatus, loadBrief } from '../store.js';
import { listAssets, assetAction, promptPack } from '../assets.js';
import { addCabinItem } from '../../cabins.js';
const seed = JSON.parse(fs.readFileSync(new URL('../../../db/seed/governance-in-testing.json', import.meta.url), 'utf8'));
const db = d1(); await ensureSchema(db); await saveDoc(db, seed);
const id = await createBrief(db, 'governance-in-testing', 'Steve');
const b0 = await loadBrief(db, id);
await patchBrief(db, id, { core: { name: 'DORA push', personas: [b0.options.personas[0].id] }, outputs: { slides: { on: true, values: { count: 5 } }, battlecard: { on: true } } });
await assert.rejects(assetAction(db, id, 'slides', { action: 'start' }), /approved brief/);
await setBriefStatus(db, id, 'locked', 'Maz (MD)');
let a = await listAssets(db, id);
assert.deepEqual(a.map((x) => x.output_id), ['slides', 'battlecard']);
assert.equal(a[0].stage, 'ordered');
await assert.rejects(assetAction(db, id, 'blog', { action: 'start' }), /not part/);
await assert.rejects(assetAction(db, id, 'slides', { action: 'approve', author: 'Maz' }), /delivered/);
a = await assetAction(db, id, 'slides', { action: 'start', author: 'Steve' });
assert.equal(a[0].stage, 'in_progress');
await assert.rejects(assetAction(db, id, 'slides', { action: 'deliver', link: 'drive' }), /full link/);
a = await assetAction(db, id, 'slides', { action: 'deliver', link: 'https://docs.google.com/presentation/d/abc', title: 'DORA slides v1', author: 'Steve' });
assert.equal(a[0].stage, 'review'); assert.equal(a[0].status, 'In progress');
await assert.rejects(assetAction(db, id, 'slides', { action: 'send_back', author: 'Maz' }), /what needs to change/);
a = await assetAction(db, id, 'slides', { action: 'send_back', note: 'Use the new logo', author: 'Maz' });
assert.equal(a[0].stage, 'in_progress');
a = await assetAction(db, id, 'slides', { action: 'deliver', link: 'https://docs.google.com/presentation/d/abc2', author: 'Steve' });
a = await assetAction(db, id, 'slides', { action: 'approve', author: 'Maz Daly (MD)' });
assert.equal(a[0].stage, 'approved'); assert.equal(a[0].status, 'Done'); assert.equal(a[0].approved_by, 'Maz Daly (MD)');
assert.deepEqual(a[0].events.map((e) => e.kind), ['started', 'delivered', 'sent_back', 'delivered', 'approved']);
a = await assetAction(db, id, 'slides', { action: 'reopen', author: 'Maz' });
assert.equal(a[0].stage, 'in_progress'); assert.equal(a[0].approved_by, null);
await addCabinItem(db, 'templates', { url: 'https://docs.google.com/presentation/d/template', name: 'Leapwork sales deck template' });
const pack = await promptPack(db, id, 'slides', 'https://antimatterconsulting.com');
assert.match(pack, /Make the "Sales slides" for Leapwork's campaign "DORA push"/);
assert.match(pack, /How many slides: 5/);
assert.match(pack, /Sales templates:\n- Leapwork sales deck template/);
assert.match(pack, new RegExp(seed.use_case.title));
console.log('asset tests ok');
