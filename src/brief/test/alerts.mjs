// Send-back email alert.
import fs from 'fs';
import assert from 'assert/strict';
import { d1 } from '../../usecase/test/d1-shim.mjs';
import { ensureSchema, saveDoc } from '../../usecase/store.js';
import { createBrief, patchBrief, setBriefStatus, loadBrief } from '../store.js';
import { assetAction } from '../assets.js';
import { sentBackAlert } from '../../alerts.js';
const seed = JSON.parse(fs.readFileSync(new URL('../../../db/seed/governance-in-testing.json', import.meta.url), 'utf8'));
const db = d1(); await ensureSchema(db); await saveDoc(db, seed);
const id = await createBrief(db, 'governance-in-testing', 'Steve');
const b0 = await loadBrief(db, id);
await patchBrief(db, id, { core: { name: 'DORA push', personas: [b0.options.personas[0].id] }, outputs: { slides: { on: true } } });
await setBriefStatus(db, id, 'locked', 'Maz');
await assetAction(db, id, 'slides', { action: 'start', author: 'Steve' });
await assetAction(db, id, 'slides', { action: 'deliver', link: 'https://docs.google.com/presentation/d/abc', title: 'DORA slides v1', author: 'Steve' });
await assetAction(db, id, 'slides', { action: 'send_back', note: 'Use the <new> logo', author: 'Maz' });
const calls = []; const fake = async (url, o) => { calls.push({ url, o }); return { ok: true, status: 200 }; };
assert.deepEqual(await sentBackAlert({}, db, id, 'slides', { note: 'x' }, 'https://x.com', fake), { sent: false, reason: 'not configured' });
assert.equal(calls.length, 0);
const r = await sentBackAlert({ RESEND_API_KEY: 'k', ALERT_TO: 'a@x.com, b@x.com', ALERT_FROM: 'M <m@x.com>' }, db, id, 'slides', { note: 'Use the <new> logo', author: 'Maz' }, 'https://x.com', fake);
assert.equal(r.sent, true); assert.equal(calls[0].url, 'https://api.resend.com/emails');
const body = JSON.parse(calls[0].o.body);
assert.deepEqual(body.to, ['a@x.com', 'b@x.com']); assert.equal(body.from, 'M <m@x.com>');
assert.equal(body.subject, 'Sent back: Sales slides · DORA push');
assert.match(body.text, /Maz sent back "Sales slides" for the DORA push campaign/);
assert.match(body.text, /Use the <new> logo/); assert.match(body.html, /Use the &lt;new&gt; logo/);
assert.match(body.text, /DORA slides v1\nhttps:\/\/docs.google.com\/presentation\/d\/abc/);
assert.equal(calls[0].o.headers.authorization, 'Bearer k');
console.log('alerts ok');
